"""
main.py
=======
Quantitative Portfolio Research & Backtesting Platform
Main execution script.

Run this script to execute the complete research pipeline:
  1. Load market data
  2. Validate data
  3. Clean data
  4. Calculate returns
  5. Generate strategy weights
  6. Run historical backtests
  7. Calculate risk metrics
  8. Compare against benchmark
  9. Store results in DuckDB
  10. Export dashboard-ready CSVs

Usage
-----
    python main.py

The script prints progress at each step so you can follow along.
All outputs are saved to:
  - data/processed/  ? cleaned prices
  - data/exports/    ? CSV files for Power BI / Tableau
  - quant_portfolio.duckdb ? DuckDB database

Expected runtime: ~30-60 seconds (mostly data download on first run)
"""

import sys
import time
from datetime import datetime

import pandas as pd
import numpy as np


def print_step(n: int, total: int, message: str) -> None:
    """Print a numbered progress step."""
    print(f"\n[{n}/{total}] {message}")
    print("-" * 60)


def main():
    print("=" * 60)
    print("  Quantitative Portfolio Research & Backtesting Platform")
    print(f"  Started: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print("=" * 60)

    TOTAL_STEPS = 10
    start_time = time.time()

    # ??????????????????????????????????????????????????????????
    # STEP 1: Load market data
    # ??????????????????????????????????????????????????????????
    print_step(1, TOTAL_STEPS, "Loading market data...")

    from src.config import (
        TICKERS,
        BENCHMARK_TICKER,
        START_DATE,
        END_DATE,
        INITIAL_CAPITAL,
        REBALANCE_FREQ,
        TRANSACTION_COST_PCT,
        RISK_FREE_RATE,
        ALL_STRATEGIES,
    )
    from src.data_loader import get_price_data, get_benchmark_data

    raw_prices = get_price_data(
        tickers=TICKERS,
        start=START_DATE,
        end=END_DATE,
        force_download=False,
    )
    print(f"  Loaded {raw_prices.shape[0]} trading days ? {raw_prices.shape[1]} tickers")
    print(f"  Date range: {raw_prices.index.min().date()} ? {raw_prices.index.max().date()}")

    # ??????????????????????????????????????????????????????????
    # STEP 2: Validate data
    # ??????????????????????????????????????????????????????????
    print_step(2, TOTAL_STEPS, "Validating data quality...")

    from src.data_cleaning import validate_data
    validation_results = validate_data(raw_prices, verbose=True)

    if not validation_results["all_passed"]:
        print("  Data validation found issues -- proceeding with cleaning step.")
    else:
        print("  Data validation passed.")

    # ??????????????????????????????????????????????????????????
    # STEP 3: Clean data
    # ??????????????????????????????????????????????????????????
    print_step(3, TOTAL_STEPS, "Cleaning and processing data...")

    from src.data_cleaning import get_clean_prices
    clean_prices = get_clean_prices(raw_prices, save=True, verbose=True)

    print(f"  Clean dataset: {clean_prices.shape[0]} rows ? {clean_prices.shape[1]} columns")
    print(f"  Tickers retained: {list(clean_prices.columns)}")

    # ??????????????????????????????????????????????????????????
    # STEP 4: Calculate returns
    # ??????????????????????????????????????????????????????????
    print_step(4, TOTAL_STEPS, "Calculating asset returns...")

    from src.returns import (
        compute_simple_returns,
        compute_log_returns,
        compute_cumulative_returns,
        build_return_summary,
    )

    simple_returns = compute_simple_returns(clean_prices)
    log_returns = compute_log_returns(clean_prices)
    cumulative_returns = compute_cumulative_returns(simple_returns)

    summary = build_return_summary(clean_prices)
    print("\n  Asset Return Summary:")
    print(summary.to_string())

    # ??????????????????????????????????????????????????????????
    # STEP 5: Generate strategy weights (for reference display)
    # ??????????????????????????????????????????????????????????
    print_step(5, TOTAL_STEPS, "Computing portfolio strategy weights...")

    from src.portfolio import equal_weight, validate_weights
    from src.optimization import (
        compute_covariance_matrix,
        minimum_variance_weights,
        risk_parity_weights,
        compute_risk_contributions,
    )

    n = len(clean_prices.columns)
    tickers = list(clean_prices.columns)

    # Compute on full historical data (for display purposes only)
    # Note: the backtest uses rolling windows -- this is just to show weights
    full_cov = compute_covariance_matrix(log_returns)

    ew_weights   = equal_weight(n)
    mv_weights   = minimum_variance_weights(full_cov)
    rp_weights   = risk_parity_weights(full_cov)

    for name, weights in [
        ("Equal Weight",       ew_weights),
        ("Minimum Variance",   mv_weights),
        ("Risk Parity",        rp_weights),
    ]:
        ok = validate_weights(weights)
        print(f"\n  {name}:")
        print(f"    Weights sum: {weights.sum():.6f}  |  Valid: {ok}")
        for ticker, w in zip(tickers, weights):
            print(f"    {ticker:8s}: {w:.4f} ({w:.1%})")

    # ??????????????????????????????????????????????????????????
    # STEP 6: Run historical backtests
    # ??????????????????????????????????????????????????????????
    print_step(6, TOTAL_STEPS, "Running historical backtests...")

    from src.backtest import run_all_strategies, combine_equity_curves, combine_weights_history

    print(f"  Rebalance frequency : {REBALANCE_FREQ}")
    print(f"  Initial capital     : ${INITIAL_CAPITAL:,.0f}")
    print(f"  Transaction cost    : {TRANSACTION_COST_PCT:.1%} per rebalance")

    backtest_results = run_all_strategies(
        prices=clean_prices,
        strategies=ALL_STRATEGIES,
        initial_capital=INITIAL_CAPITAL,
        rebalance_freq=REBALANCE_FREQ,
        transaction_cost_pct=TRANSACTION_COST_PCT,
        verbose=False,
    )

    equity_curves = combine_equity_curves(backtest_results, normalize=True)
    combined_weights = combine_weights_history(backtest_results)

    print(f"\n  Backtest complete. {len(equity_curves)} trading days simulated.")

    # ??????????????????????????????????????????????????????????
    # STEP 7: Calculate risk metrics
    # ??????????????????????????????????????????????????????????
    print_step(7, TOTAL_STEPS, "Calculating risk and performance metrics...")

    from src.benchmark import load_and_prepare_benchmark
    from src.risk_metrics import compute_all_metrics

    benchmark_returns = load_and_prepare_benchmark(clean_prices)

    strategy_metrics = {}
    for strategy_name, result in backtest_results.items():
        metrics = compute_all_metrics(
            equity_curve=result["portfolio_values"],
            daily_returns=result["daily_returns"],
            benchmark_returns=benchmark_returns,
            strategy_name=strategy_name,
            risk_free_rate=RISK_FREE_RATE,
        )
        strategy_metrics[strategy_name] = metrics

    print("  Risk metrics computed for all strategies.")

    # ??????????????????????????????????????????????????????????
    # STEP 8: Compare against benchmark
    # ??????????????????????????????????????????????????????????
    print_step(8, TOTAL_STEPS, "Comparing strategies against benchmark...")

    from src.benchmark import run_benchmark_comparison, compute_benchmark_metrics

    comparison_df = run_benchmark_comparison(
        backtest_results=backtest_results,
        benchmark_returns=benchmark_returns,
        risk_free_rate=RISK_FREE_RATE,
    )

    # Build all_metrics dict (includes benchmark) for DB + export
    from src.config import BENCHMARK_NAME
    all_metrics = dict(strategy_metrics)
    all_metrics[BENCHMARK_NAME] = compute_benchmark_metrics(benchmark_returns)

    # ??????????????????????????????????????????????????????????
    # STEP 9: Store results in DuckDB
    # ??????????????????????????????????????????????????????????
    print_step(9, TOTAL_STEPS, "Storing data and results in DuckDB...")

    from src.database import store_all_results

    store_all_results(
        prices=clean_prices,
        backtest_results=backtest_results,
        combined_weights=combined_weights,
        all_metrics=all_metrics,
    )

    # ??????????????????????????????????????????????????????????
    # STEP 10: Export dashboard datasets
    # ??????????????????????????????????????????????????????????
    print_step(10, TOTAL_STEPS, "Exporting dashboard-ready CSV files...")

    from src.export_results import export_all

    export_all(
        backtest_results=backtest_results,
        all_metrics=all_metrics,
        combined_weights=combined_weights,
        comparison_df=comparison_df,
        benchmark_returns=benchmark_returns,
        prices=clean_prices,
    )

    # ??????????????????????????????????????????????????????????
    # DONE
    # ??????????????????????????????????????????????????????????
    elapsed = time.time() - start_time
    print("\n" + "=" * 60)
    print("  Pipeline Complete!")
    print(f"  Total runtime: {elapsed:.1f} seconds")
    print()
    print("  Output files:")
    print("    data/processed/prices_clean.csv")
    print("    data/exports/strategy_performance.csv")
    print("    data/exports/risk_metrics.csv")
    print("    data/exports/portfolio_weights.csv")
    print("    data/exports/benchmark_comparison.csv")
    print("    data/exports/asset_returns.csv")
    print("    quant_portfolio.duckdb")
    print()
    print("  Next steps:")
    print("    ? Open notebooks/ in Jupyter for visual analysis")
    print("    ? Import data/exports/*.csv into Power BI or Tableau")
    print("    ? Run 'pytest tests/ -v' to verify calculations")
    print("=" * 60)


if __name__ == "__main__":
    main()
